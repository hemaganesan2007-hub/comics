import { jsPDF } from 'jspdf';

export interface PanelData {
  panel_number: number;
  title: string;
  scene_description: string;
  image_prompt: string;
  caption: string;
  narration: string;
  dialogue: string;
  action: string;
  emotional_context: string;
  image_path: string;
}

export function exportComicToPDF(
  panels: PanelData[],
  storyPrompt: string,
  characterName: string,
  setting: string,
  tone: string,
  artStyle: string,
  generationId: string
) {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 14;

  // Cover / Header Banner
  doc.setFillColor(254, 243, 199); // Amber-100
  doc.rect(margin, margin, pageWidth - margin * 2, 42, 'F');
  doc.setDrawColor(24, 24, 27);
  doc.setLineWidth(0.8);
  doc.rect(margin, margin, pageWidth - margin * 2, 42, 'S');

  // Title
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(22);
  doc.setTextColor(180, 83, 9); // Amber-700
  doc.text('COMICCRAFT ARCHIVE', pageWidth / 2, margin + 14, { align: 'center' });

  // Story Premise
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(24, 24, 27);
  const titleText = `"${storyPrompt.slice(0, 65)}"`;
  doc.text(titleText, pageWidth / 2, margin + 24, { align: 'center' });

  // Metadata attributes
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(100, 116, 139);
  doc.text(
    `Protagonist: ${characterName}  |  Setting: ${setting}  |  Tone: ${tone}  |  Style: ${artStyle}  |  ID: ${generationId}`,
    pageWidth / 2,
    margin + 33,
    { align: 'center' }
  );

  let currentY = margin + 50;

  // Render each of the 5 panels
  panels.forEach((panel) => {
    // Check page overflow
    if (currentY + 45 > pageHeight - margin) {
      doc.addPage();
      currentY = margin + 8;
    }

    // Panel Header Bar
    doc.setFillColor(30, 41, 59); // Slate-800
    doc.rect(margin, currentY, pageWidth - margin * 2, 7, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10);
    doc.setTextColor(255, 255, 255);
    doc.text(` PANEL #${panel.panel_number}: ${panel.title.toUpperCase()}`, margin + 3, currentY + 5);

    const panelTopY = currentY + 9;

    // Panel Illustration placeholder / frame
    const imgSize = 36;
    doc.setFillColor(248, 250, 252);
    doc.rect(margin, panelTopY, imgSize, imgSize, 'F');
    doc.setDrawColor(24, 24, 27);
    doc.setLineWidth(0.6);
    doc.rect(margin, panelTopY, imgSize, imgSize, 'S');

    // Comic mini-badge inside image
    doc.setFillColor(245, 158, 11);
    doc.rect(margin + 2, panelTopY + 2, 22, 6, 'F');
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(7);
    doc.setTextColor(24, 24, 27);
    doc.text(`PANEL #${panel.panel_number}`, margin + 4, panelTopY + 6.5);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(100, 116, 139);
    doc.text('[AI Illustration]', margin + 6, panelTopY + 22);

    // Text Column
    const textX = margin + imgSize + 6;
    const textWidth = pageWidth - margin * 2 - imgSize - 8;
    let textY = panelTopY + 3;

    // Caption
    if (panel.caption) {
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(8.5);
      doc.setTextColor(217, 119, 6);
      doc.text(`[CAPTION: ${panel.caption.toUpperCase()}]`, textX, textY);
      textY += 4.5;
    }

    // Narration
    if (panel.narration) {
      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8.5);
      doc.setTextColor(30, 41, 59);
      const narrationLines = doc.splitTextToSize(panel.narration, textWidth);
      doc.text(narrationLines, textX, textY);
      textY += narrationLines.length * 3.8 + 1.5;
    }

    // Dialogue Bubble
    if (panel.dialogue) {
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9);
      doc.setTextColor(15, 23, 42);
      const dialogueLines = doc.splitTextToSize(panel.dialogue, textWidth);
      doc.text(dialogueLines, textX, textY);
      textY += dialogueLines.length * 4 + 1.5;
    }

    // Scene Description
    if (panel.scene_description) {
      doc.setFont('helvetica', 'italic');
      doc.setFontSize(7.5);
      doc.setTextColor(100, 116, 139);
      const sceneLines = doc.splitTextToSize(`Scene: ${panel.scene_description}`, textWidth);
      doc.text(sceneLines, textX, textY);
      textY += sceneLines.length * 3.4;
    }

    currentY = Math.max(panelTopY + imgSize + 5, textY + 4);
  });

  // Footer on current page
  doc.setFont('helvetica', 'italic');
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text(
    `Generated by ComicCraft with Gemini AI & Stable Diffusion | ${new Date().toLocaleDateString()}`,
    pageWidth / 2,
    pageHeight - 8,
    { align: 'center' }
  );

  const timestamp = new Date().toISOString().replace(/[-:T.]/g, '').slice(0, 14);
  doc.save(`comic_${timestamp}_${generationId}.pdf`);
}
