"""
Gemini Pro Story Generator Module.
Generates detailed narration, character dialogue, captions, actions, and emotional context
for each of the 5 panels from the structured outline.
"""

import json
import os
import re
import logging
from typing import List, Dict, Any

logger = logging.getLogger(__name__)

STORY_SYSTEM_PROMPT = """You are a professional comic scriptwriter.
Given a 5-panel comic outline and user parameters (Character, Setting, Tone, Art Style),
you write vivid, punchy comic script elements for each panel:
- Caption: Short, impactful editorial or narrative box at the top (e.g., "Deep within the whisper woods...")
- Narration: Descriptive voiceover setting the immediate scene mood
- Dialogue: Spoken words by the character or surrounding entities (e.g., Finn: "I knew the legends were real!")
- Action: Brief cinematic action tag describing movement or physical interaction
- Emotional Context: The interior feeling (e.g., "Curiosity tinged with nervous anticipation")

Return a STRICT JSON array of exactly 5 objects matching the 5 panels:
[
  {
    "panel_number": 1,
    "caption": "...",
    "narration": "...",
    "dialogue": "Character Name: \\"...\\"",
    "action": "...",
    "emotional_context": "..."
  },
  ...
]
"""

def clean_json_response(raw_text: str) -> str:
    """Removes markdown code fences and extracts raw JSON string."""
    cleaned = raw_text.strip()
    code_block_match = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", cleaned, re.IGNORECASE)
    if code_block_match:
        return code_block_match.group(1).strip()
    return cleaned

def generate_story(
    outline: List[Dict[str, Any]],
    story_prompt: str,
    character_name: str,
    setting: str,
    tone: str,
    art_style: str
) -> List[Dict[str, Any]]:
    """
    Calls Gemini Pro / capable model to generate detailed comic text for each panel.
    
    Args:
        outline: The 5-panel outline generated by Gemini Flash.
        story_prompt: The user's creative core prompt.
        character_name: Name of the main character.
        setting: Story setting.
        tone: Tone of the comic (Light-hearted, Dramatic, Poetic, Funny).
        art_style: Chosen art style.
        
    Returns:
        List of 5 panel story dictionaries with caption, narration, dialogue, action, emotional_context.
    """
    api_key = os.getenv("GEMINI_API_KEY")

    outline_summary = json.dumps(outline, indent=2)
    user_instructions = f"""Expand the following 5-panel outline into a complete comic script:
Story Premise: {story_prompt}
Main Character: {character_name}
Setting: {setting}
Tone: {tone}
Art Style: {art_style}

Input Outline:
{outline_summary}

Requirements:
1. Provide rich, creative text for every panel (1 to 5).
2. Deeply reflect the requested '{tone}' tone (e.g. if Funny, use comedic banter and humorous captions; if Dramatic, emphasize high stakes and tension).
3. The Dialogue must clearly feature {character_name} speaking.
4. Output MUST be valid JSON array of 5 objects containing keys: panel_number, caption, narration, dialogue, action, emotional_context.
"""

    if api_key and api_key != "your_gemini_api_key_here":
        try:
            try:
                from google import genai
                from google.genai import types
                client = genai.Client(api_key=api_key, http_options={"headers": {"User-Agent": "aistudio-build"}})
                response = client.models.generate_content(
                    model="gemini-3.8-flash",  # High-performance server model
                    contents=user_instructions,
                    config=types.GenerateContentConfig(
                        system_instruction=STORY_SYSTEM_PROMPT,
                        temperature=0.85,
                        response_mime_type="application/json"
                    )
                )
                raw_text = response.text or ""
            except ImportError:
                import google.generativeai as legacy_genai
                legacy_genai.configure(api_key=api_key)
                model = legacy_genai.GenerativeModel(
                    model_name="gemini-1.5-pro",
                    system_instruction=STORY_SYSTEM_PROMPT
                )
                response = model.generate_content(
                    user_instructions,
                    generation_config={"response_mime_type": "application/json", "temperature": 0.85}
                )
                raw_text = response.text or ""

            cleaned_json = clean_json_response(raw_text)
            parsed_data = json.loads(cleaned_json)

            if isinstance(parsed_data, dict):
                for key in ["panels", "story", "comic", "script"]:
                    if key in parsed_data and isinstance(parsed_data[key], list):
                        parsed_data = parsed_data[key]
                        break

            if isinstance(parsed_data, list) and len(parsed_data) == 5:
                validated_story = []
                for idx, item in enumerate(parsed_data, start=1):
                    validated_story.append({
                        "panel_number": int(item.get("panel_number", idx)),
                        "caption": str(item.get("caption", f"Panel {idx}")).strip(),
                        "narration": str(item.get("narration", "")).strip(),
                        "dialogue": str(item.get("dialogue", f'{character_name}: "..."')).strip(),
                        "action": str(item.get("action", "")).strip(),
                        "emotional_context": str(item.get("emotional_context", tone)).strip()
                    })
                return validated_story
        except Exception as e:
            logger.error("Error calling Gemini Pro for story expansion: %s. Using tailored fallback.", str(e))

    return generate_fallback_story(outline, character_name, setting, tone)


def generate_fallback_story(
    outline: List[Dict[str, Any]],
    character_name: str,
    setting: str,
    tone: str
) -> List[Dict[str, Any]]:
    """Generates context-rich story dialogue, narration, and captions adapted to tone."""
    tone_lower = tone.lower()
    
    tone_dialogues = {
        "funny": [
            f'{character_name}: "Note to self: never volunteer as tribute on a Monday."',
            f'{character_name}: "Well, it sparkles... so either it\'s ancient magic or someone dropped their glitter shaker."',
            f'{character_name}: "Okay, don\'t panic! Panicking burns precious calories!"',
            f'{character_name}: "Whoops! That definitely wasn\'t in the user manual!"',
            f'{character_name}: "And they said I\'d never amount to anything! Take that, middle school guidance counselor!"'
        ],
        "dramatic": [
            f'{character_name}: "The silence here is deafening. There\'s no turning back now."',
            f'{character_name}: "It\'s real... the ancient prophecy wasn\'t a myth after all."',
            f'{character_name}: "I have to stand my ground. If I run now, everything falls."',
            f'{character_name}: "With all the strength left in my soul—NOW!"',
            f'{character_name}: "The storm has passed. But our world will never be the same."'
        ],
        "poetic": [
            f'{character_name}: "Beneath the canopy of forgotten stars, breath intertwines with eternity."',
            f'{character_name}: "A beacon in the shadow—a gentle song sung only in light."',
            f'{character_name}: "The wind howls of sorrow, yet the spirit burns undaunted."',
            f'{character_name}: "Here at the crossroads of fate, courage blooms like spring blossom."',
            f'{character_name}: "Peace rests upon the horizon, woven in silence and starlight."'
        ],
        "light-hearted": [
            f'{character_name}: "What a fantastic morning for a grand adventure!"',
            f'{character_name}: "Aha! Look what we stumbled upon! Isn\'t this marvelous?"',
            f'{character_name}: "Just a little bump in the road. We can totally handle this!"',
            f'{character_name}: "Here goes nothing! Leap high and believe!"',
            f'{character_name}: "We did it! Time to celebrate and map out our next voyage!"'
        ]
    }
    
    dialogue_set = tone_dialogues.get(tone_lower, tone_dialogues["dramatic"])
    captions = [
        f"Chapter I: The Arrival in the {setting}",
        f"Chapter II: The Enigma Unveiled",
        f"Chapter III: The Trial of Will",
        f"Chapter IV: The Defining Clash",
        f"Chapter V: Triumph and Reflections"
    ]

    narrations = [
        f"The tranquil horizons of {setting} offer no hint of the trials about to unfold.",
        f"Hidden within the shadows, an ancient secret begins to stir.",
        f"Tension mounts as unexpected peril demands swift decisive action.",
        f"In a flash of blinding resolve, the fate of the journey hangs in the balance.",
        f"Serenity returns, marking the dawn of a legendary tale."
    ]

    story = []
    for i in range(5):
        story.append({
            "panel_number": i + 1,
            "caption": captions[i],
            "narration": narrations[i],
            "dialogue": dialogue_set[i],
            "action": f"{character_name} moves decisively in the {setting.lower()}.",
            "emotional_context": tone
        })
    return story
