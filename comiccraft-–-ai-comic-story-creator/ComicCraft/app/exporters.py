"""
PDF Exporter Module.
Generates a multi-page, publication-ready comic book PDF using FPDF/fpdf2.
"""

import os
from datetime import datetime
from pathlib import Path
from typing import List, Dict, Any
from fpdf import FPDF

BASE_DIR = Path(__file__).resolve().parent.parent
STATIC_DIR = BASE_DIR / "static"
EXPORTS_DIR = STATIC_DIR / "exports"
EXPORTS_DIR.mkdir(parents=True, exist_ok=True)


class ComicPDF(FPDF):
    """Custom FPDF class with comic-themed header, footer, and styling."""

    def __init__(self, comic_title: str):
        super().__init__(orientation="P", unit="mm", format="A4")
        self.comic_title = self._sanitize(comic_title)
        self.set_auto_page_break(auto=True, margin=15)

    def _sanitize(self, text: str) -> str:
        """Sanitizes text to prevent Latin-1 encoding errors in standard PDF fonts."""
        if not text:
            return ""
        # Common unicode typography replacements
        replacements = {
            "\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"',
            "\u2014": "--", "\u2013": "-", "\u2026": "...", "\u2022": "*",
            "’": "'", "‘": "'", "“": '"', "”": '"', "—": "--", "–": "-",
            "…": "..."
        }
        for orig, rep in replacements.items():
            text = text.replace(orig, rep)
        # Encode with replacement for unrepresented characters
        return text.encode("latin-1", "replace").decode("latin-1")

    def header(self):
        if self.page_no() > 1:
            self.set_font("Helvetica", "B", 9)
            self.set_text_color(120, 120, 120)
            self.cell(0, 8, f"ComicCraft: {self.comic_title}", border=0, align="L")
            self.ln(10)

    def footer(self):
        self.set_y(-12)
        self.set_font("Helvetica", "I", 8)
        self.set_text_color(150, 150, 150)
        self.cell(0, 8, f"Page {self.page_no()} | Generated by ComicCraft with Gemini AI", border=0, align="C")


def save_pdf(
    layout: List[Dict[str, Any]],
    story_prompt: str,
    character_name: str,
    setting: str,
    tone: str,
    art_style: str,
    generation_id: str = ""
) -> str:
    """
    Renders all 5 comic panels into a multi-page PDF saved under static/exports/.
    
    Args:
        layout: List of 5 panel dictionaries containing title, scene_description,
                image_path, caption, narration, dialogue.
        story_prompt: Original user premise.
        character_name: Main character name.
        setting: Story setting.
        tone: Emotional tone.
        art_style: Art style.
        generation_id: Unique generation identifier.
        
    Returns:
        Web-accessible relative URL (e.g. '/static/exports/comic_20260930_123456.pdf').
    """
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    safe_gen = f"_{generation_id}" if generation_id else ""
    filename = f"comic_{timestamp}{safe_gen}.pdf"
    file_path = EXPORTS_DIR / filename

    pdf = ComicPDF(f"{character_name}'s Tale: {story_prompt[:30]}")

    # --- COVER PAGE ---
    pdf.add_page()
    pdf.set_fill_color(254, 243, 199)  # Light amber comic banner
    pdf.rect(10, 10, 190, 45, "F")

    # Main Comic Title
    pdf.set_xy(15, 16)
    pdf.set_font("Helvetica", "B", 24)
    pdf.set_text_color(180, 83, 9)  # Amber-700
    pdf.cell(180, 12, pdf._sanitize("COMICCRAFT ARCHIVE"), ln=True, align="C")

    pdf.set_xy(15, 30)
    pdf.set_font("Helvetica", "B", 14)
    pdf.set_text_color(30, 41, 59)
    pdf.cell(180, 8, pdf._sanitize(f"\"{story_prompt[:60]}\""), ln=True, align="C")

    pdf.set_xy(15, 40)
    pdf.set_font("Helvetica", "I", 10)
    pdf.set_text_color(100, 116, 139)
    pdf.cell(180, 6, pdf._sanitize(f"Protagonist: {character_name} | Setting: {setting} | Tone: {tone} | Style: {art_style}"), ln=True, align="C")

    pdf.ln(12)

    # --- RENDER PANELS ---
    for panel in layout:
        # Check remaining page height, add page if less than 85mm remaining
        if pdf.get_y() > 200:
            pdf.add_page()

        panel_num = panel.get("panel_number", 1)
        title = panel.get("title", f"Panel {panel_num}")
        caption = panel.get("caption", "")
        narration = panel.get("narration", "")
        dialogue = panel.get("dialogue", "")
        scene_desc = panel.get("scene_description", "")
        img_rel_path = panel.get("image_path", "")

        # Panel Header Box
        pdf.set_fill_color(30, 41, 59)  # Dark slate
        pdf.set_text_color(255, 255, 255)
        pdf.set_font("Helvetica", "B", 11)
        pdf.cell(190, 7, pdf._sanitize(f" PANEL {panel_num}: {title.upper()}"), ln=True, fill=True)

        y_after_header = pdf.get_y()

        # Image placement on left column (width: 55mm, height: 55mm)
        img_rendered = False
        if img_rel_path:
            # Strip leading slash if any to build absolute path
            clean_rel = img_rel_path.lstrip("/")
            full_img_path = BASE_DIR / clean_rel
            if full_img_path.exists():
                try:
                    pdf.image(str(full_img_path), x=12, y=y_after_header + 2, w=52, h=52)
                    img_rendered = True
                except Exception as err:
                    pass

        # Text on right column
        text_x = 68 if img_rendered else 14
        text_w = 132 if img_rendered else 186
        pdf.set_xy(text_x, y_after_header + 2)

        # Caption Tag
        if caption:
            pdf.set_font("Helvetica", "B", 9)
            pdf.set_text_color(217, 119, 6)  # Amber
            pdf.multi_cell(text_w, 4.5, pdf._sanitize(f"[{caption.upper()}]"))
            pdf.set_x(text_x)

        # Narration
        if narration:
            pdf.set_font("Helvetica", "", 9)
            pdf.set_text_color(40, 40, 40)
            pdf.multi_cell(text_w, 4.5, pdf._sanitize(narration))
            pdf.set_x(text_x)

        # Dialogue Bubble simulation
        if dialogue:
            pdf.ln(1)
            pdf.set_x(text_x)
            pdf.set_font("Helvetica", "B", 9.5)
            pdf.set_text_color(15, 23, 42)
            pdf.multi_cell(text_w, 4.5, pdf._sanitize(dialogue))
            pdf.set_x(text_x)

        # Scene description (italicized)
        if scene_desc:
            pdf.ln(1)
            pdf.set_x(text_x)
            pdf.set_font("Helvetica", "I", 8)
            pdf.set_text_color(100, 116, 139)
            pdf.multi_cell(text_w, 4, pdf._sanitize(f"Scene: {scene_desc}"))

        # Advance below image or text, whichever is taller
        current_y = pdf.get_y()
        target_y = max(current_y, y_after_header + 56)
        pdf.set_y(target_y + 4)

    pdf.output(str(file_path))
    return f"/static/exports/{filename}"
